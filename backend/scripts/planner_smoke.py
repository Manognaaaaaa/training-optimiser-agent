"""Live smoke test of the agent planner against the real Groq API.

Run from the backend folder:   python -m scripts.planner_smoke [--n 5] [--alerts 3]

It builds its OWN database (backend/smoke.db, seed 42, played to about week 20), so training.db is never touched.
It writes docs/planner_report.md with real numbers. If GROQ_API_KEY is empty it says so and exits 0.
"""
import argparse
import sys
from collections import Counter
from datetime import date
from pathlib import Path

from sqlalchemy import create_engine, select
from sqlalchemy.orm import Session

from app.config import settings
from app.llm import llm_configured
from app.llm.groq_client import build_groq_client
from app.llm.planner import run_planner
from app.models import Alert, Course, Plan, PlannerRun
from app.routers.planner import _Labels, metrics
from app.simulator.engine import advance
from app.simulator.seed import reseed

SMOKE_DB = Path(__file__).resolve().parent.parent / "smoke.db"
REPORT = Path(__file__).resolve().parents[2] / "docs" / "planner_report.md"
SEED = 42
DAYS = 140  # about week 20


def pick_alerts(db: Session, wanted: int) -> list[Alert]:
    """Open alerts, preferring one of each shortfall type."""
    alerts = list(db.scalars(select(Alert).where(Alert.status == "open").order_by(Alert.id)))
    chosen, seen_types = [], set()
    for a in alerts:
        if a.shortfall_type not in seen_types:
            chosen.append(a)
            seen_types.add(a.shortfall_type)
    for a in alerts:  # top up with any other open alerts
        if len(chosen) >= wanted:
            break
        if a not in chosen:
            chosen.append(a)
    return chosen[:wanted]


def write_report(db: Session, runs: list[PlannerRun], model: str) -> str:
    m = metrics(db)
    lines = [
        "# Agent planner report", "",
        f"Generated by `python -m scripts.planner_smoke` on {date.today():%Y-%m-%d} (real date; the simulation clock is separate).", "",
        f"- Model: `{model}`", f"- Prompt version: `{runs[0].prompt_version}`", f"- Seed: {SEED}, simulation played {DAYS} days",
        f"- Samples per alert: {runs[0].n_requested}", "",
        "## Per alert", "",
        "| Alert | Course | Shortfall | Valid | Invalid | Schema invalid | No plan | Step limit | Duplicate | Status |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for run in runs:
        alert = db.get(Alert, run.alert_id)
        course = db.get(Course, run.course_id)
        lines.append(
            f"| {alert.id} | {course.code} | {alert.shortfall_type} | {run.n_valid} | {run.n_invalid} | {run.n_schema_invalid} | "
            f"{run.n_no_plan} | {run.n_step_limit} | {run.n_duplicates} | {run.status}{(': ' + run.error) if run.error else ''} |"
        )

    plans = list(db.scalars(select(Plan).where(Plan.run_id.is_not(None))))
    codes = Counter(v["code"] for p in plans for v in (p.rejection_reasons or []))
    lines += ["", "## Violations the checker found", ""]
    if codes:
        lines += ["| Code | Count |", "|---|---|"] + [f"| {code} | {n} |" for code, n in codes.most_common()]
    else:
        lines.append("None.")

    catch = "n/a (no fabricated IDs)" if m["checker_catch_rate"] is None else f"{m['checker_catch_rate'] * 100:.0f}%"
    lines += [
        "", "## Hallucination check", "",
        f"- Plans stored: {m['plans_total']}",
        f"- Plans with a hallucinated reference: {m['hallucination_pct']}%",
        f"- Fabricated IDs: {m['fabricated_ids_total']} (caught by the checker: {m['fabricated_ids_caught']}, catch rate {catch})",
        f"- Valid plans: {m['valid_pct']}%, schema-invalid: {m['schema_invalid_pct']}%", "",
        "## Cost per sample", "",
        f"- Average steps: {m['avg_steps']}", f"- Average tokens: {m['avg_tokens']}", f"- Average latency: {m['avg_latency_ms'] / 1000:.1f}s", "",
        "## Example valid plan", "",
    ]
    example = next((p for p in plans if p.outcome == "valid"), None)
    if example is None:
        lines.append("No valid plan was produced in this run.")
    else:
        labels = _Labels(db, [example])
        lines += [f"Alert {example.alert_id}, sample {example.sample_index + 1}, strategy: {example.strategy}, temperature {example.temperature}.", ""]
        lines += [f"1. {label}" for label in (labels.action(a) for a in example.actions)]
        lines += ["", f"Rationale: {example.rationale or '(none given)'}"]
    text = "\n".join(lines) + "\n"
    REPORT.write_text(text, encoding="utf-8")
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description="Run the agent planner against the real Groq API.")
    parser.add_argument("--n", type=int, default=settings.planner_default_n, help="samples per alert")
    parser.add_argument("--alerts", type=int, default=3, help="how many alerts to plan for")
    args = parser.parse_args()

    if not llm_configured():
        print("GROQ_API_KEY is not set in backend/.env, so there is nothing to smoke-test. Exiting without a report.")
        return 0

    if SMOKE_DB.exists():
        SMOKE_DB.unlink()
    engine = create_engine(f"sqlite:///{SMOKE_DB}")
    print(f"Seeding {SMOKE_DB.name} (seed {SEED}) and playing {DAYS} days...")
    reseed(engine, SEED)
    llm = build_groq_client()
    with Session(engine, expire_on_commit=False, autoflush=False) as db:
        advance(db, DAYS)
        alerts = pick_alerts(db, args.alerts)
        if not alerts:
            print("No open alerts after the fast-forward; nothing to plan for.")
            return 0
        runs = []
        for alert in alerts:
            print(f"Alert {alert.id} ({alert.shortfall_type}): {args.n} samples...")
            run = run_planner(db, alert.id, args.n, llm)
            print(f"  {run.status}: {run.n_valid} valid, {run.n_invalid} invalid, {run.n_schema_invalid} schema invalid, "
                  f"{run.n_no_plan} no plan, {run.n_step_limit} step limit, {run.n_duplicates} duplicates {run.error or ''}")
            runs.append(run)
        write_report(db, runs, runs[-1].model)
    print(f"Wrote {REPORT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
