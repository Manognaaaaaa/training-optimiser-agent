"""Live smoke test of the whole Phase 6 pipeline against the real LLM.

Run from the backend folder:   python -m scripts.smoke_phase6 [--n 3] [--alerts 3]

For each chosen alert it runs the planner, ranks the valid plans, writes and grounding-checks the alert message,
then approves the top plan of the first alert that has one and rejects the top plan of the second.
It builds its OWN database (backend/smoke.db, seed 42, played about 20 weeks), so training.db is never touched,
and writes docs/alerts_report.md. If no LLM key is set it says so and exits 0.
"""
import argparse
import statistics
import sys
from datetime import date
from pathlib import Path

from sqlalchemy import create_engine, select
from sqlalchemy.orm import Session

from app.llm import llm_configured
from app.llm.groq_client import build_groq_client
from app.llm.planner import run_planner
from app.models import Alert, AlertMessage, Course, Plan, PlannerRun
from app.services import decisions
from app.services.errors import ApiError
from app.simulator.engine import advance
from app.simulator.seed import reseed

SMOKE_DB = Path(__file__).resolve().parent.parent / "smoke.db"
REPORT = Path(__file__).resolve().parents[2] / "docs" / "alerts_report.md"
SEED = 42
DAYS = 140


def pick_alerts(db: Session, wanted: int) -> list[Alert]:
    """Open alerts, one per shortfall type first."""
    alerts = list(db.scalars(select(Alert).where(Alert.status == "open").order_by(Alert.id)))
    chosen, seen = [], set()
    for a in alerts:
        if a.shortfall_type not in seen:
            chosen.append(a)
            seen.add(a.shortfall_type)
    for a in alerts:
        if len(chosen) >= wanted:
            break
        if a not in chosen:
            chosen.append(a)
    return chosen[:wanted]


def pct(part: int, whole: int) -> str:
    return f"{100 * part / whole:.0f}%" if whole else "n/a"


def write_report(db: Session, alert_ids: list[int], runs: list[PlannerRun], actions: list[str], model: str) -> None:
    messages = list(db.scalars(select(AlertMessage).where(AlertMessage.alert_id.in_(alert_ids)).order_by(AlertMessage.id)))
    first = [m for m in messages if m.attempts == 1 and not m.used_fallback and m.prompt_version]
    llm_rows = [m for m in messages if m.model != "template"]
    first_pass = [m for m in first if m.grounding_ok]
    finals = {}  # alert id -> last message row
    for m in messages:
        finals[m.alert_id] = m
    retried = sum(1 for m in llm_rows if m.attempts == 2)
    fallbacks = sum(1 for m in finals.values() if m.used_fallback)
    latencies = [m.latency_ms for m in llm_rows if m.latency_ms]

    lines = [
        "# Ranking and alerts report", "",
        f"Generated by `python -m scripts.smoke_phase6` on {date.today():%Y-%m-%d} (real date; the simulation clock is separate).", "",
        f"- Model: `{model}`, seed {SEED}, simulation played {DAYS} days, {runs[0].n_requested} samples per alert", "",
        "## Per alert", "",
        "| Alert | Course | Shortfall | Valid plans | Score spread (best / worst) | Final status |",
        "|---|---|---|---|---|---|",
    ]
    for run in runs:
        alert = db.get(Alert, run.alert_id)
        course = db.get(Course, run.course_id)
        scores = [p.score_total for p in db.scalars(select(Plan).where(Plan.run_id == run.id, Plan.rank.is_not(None))) if p.score_total is not None]
        spread = f"{max(scores):.2f} / {min(scores):.2f}" if scores else "no valid plans"
        lines.append(f"| {alert.id} | {course.code} | {alert.shortfall_type} | {len(scores)} | {spread} | {alert.status} |")

    lines += [
        "", "## Alert message quality", "",
        f"- Grounding pass rate on the first attempt: {pct(len(first_pass), len(first))} ({len(first_pass)} of {len(first)})",
        f"- Retry rate (a second LLM attempt was needed): {pct(retried, len(first))}",
        f"- Fallback rate (template used): {pct(fallbacks, len(finals))} ({fallbacks} of {len(finals)} alerts)",
        f"- Average message latency: {statistics.mean(latencies):.0f} ms" if latencies else "- Average message latency: n/a",
        "", "## Decisions made by the script", "",
    ]
    lines += [f"- {a}" for a in actions] or ["- none (no alert had a valid plan)"]

    lines += ["", "## Example message per alert", ""]
    for alert_id in alert_ids:
        row = finals.get(alert_id)
        alert = db.get(Alert, alert_id)
        if row is None:
            continue
        msg = row.parsed or {}
        source = "template" if row.used_fallback else "LLM"
        lines += [
            f"### Alert {alert_id}: {alert.shortfall_type} ({source}, grounding {'passed' if row.grounding_ok else 'FAILED'})", "",
            f"**{msg.get('headline', '')}**", "", msg.get("summary", ""), "",
        ]
        lines += [f"- {b}" for b in msg.get("why_at_risk", [])] + [""]
        for p in msg.get("plans", []):
            lines.append(f"- Plan {p['plan_id']}: {p['rationale']} _{p['tradeoffs']}_")
        lines.append("")
    REPORT.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--n", type=int, default=3, help="plans to sample per alert")
    parser.add_argument("--alerts", type=int, default=3, help="how many alerts to run")
    args = parser.parse_args()
    if not llm_configured():
        print("No LLM key is set (GROQ_API_KEY in backend/.env). Nothing was run.")
        return 0

    SMOKE_DB.unlink(missing_ok=True)
    engine = create_engine(f"sqlite:///{SMOKE_DB}")
    reseed(engine, SEED)
    llm = build_groq_client()
    runs: list[PlannerRun] = []
    actions: list[str] = []
    with Session(engine, expire_on_commit=False, autoflush=False) as db:
        advance(db, DAYS)
        alerts = pick_alerts(db, args.alerts)
        alert_ids = [a.id for a in alerts]
        for alert in alerts:
            print(f"Alert {alert.id} ({alert.shortfall_type}): running {args.n} samples...")
            runs.append(run_planner(db, alert.id, args.n, llm))
            db.refresh(alert)
            print(f"  status: {alert.status}")

        decided = 0
        for alert_id in alert_ids:
            top = db.scalar(select(Plan).where(Plan.alert_id == alert_id, Plan.rank == 1, Plan.status == "valid"))
            if top is None or decided >= 2:
                continue
            try:
                if decided == 0:
                    decisions.approve_plan(db, top.id, 1)
                    actions.append(f"Approved plan {top.id} (rank 1) of alert {alert_id}.")
                else:
                    decisions.reject_plan(db, top.id, 1, "too_disruptive", None)
                    actions.append(f"Rejected plan {top.id} (rank 1) of alert {alert_id} as too disruptive.")
            except ApiError as err:
                actions.append(f"Plan {top.id} of alert {alert_id} could not be decided: {err.detail}")
            decided += 1
        write_report(db, alert_ids, runs, actions, getattr(llm, "model", ""))
    print(f"Report written to {REPORT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
